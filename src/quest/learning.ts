export function learningFor(songId: string, grade: GradeBand = '3-4'): LearningPack {
  const plan = Object.hasOwn(plans, songId) ? plans[songId] : fallback;
  const band = grade === '5-6' ? 1 : 0;
  const selected = plan.topics.map(id => topics[id]);
  const groups = [selected.slice(0, 2), selected.slice(2, 4), selected.slice(4)];
  return {
    grade,
    concepts: groups.map((group, index) => ({
      title: group.map(topic => topic.title).join(' / '),
      body: `${index === 0 ? `${plan.title}: ${plan.listen} ` : ''}${group.map(topic => topic.notes[band]).join(' ')}`,
    })),
    questions: selected.map((topic, index) => {
      const [q, right, wrong1, wrong2, why] = topic.tasks[band];
      const correct = (index + band) % 3;
      const a = [wrong1, wrong2];
      a.splice(correct, 0, right);
      return { q, a, correct, why, concept: topic.title };
    }),
    sourceUrls: [
      'https://www.moe.go.kr/boardCnts/viewRenew.do?boardID=141&boardSeq=93458&lev=0&m=0302',
      'https://www.moe.go.kr/boardCnts/fileDown.do?fileSeq=1512facbda6c234a1641ac7e9c156ca2&m=0302&s=moe',
    ],
  };
}
